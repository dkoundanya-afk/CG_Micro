using UnityEngine;

namespace ZBufferDemo
{
    /// <summary>
    /// Interactive controller for the Phase 4 Z-Buffer Occlusion Demonstration.
    /// Demonstrates pixel-level depth testing using an array of overlapping calibration slabs
    /// and a dynamic sliding probe.
    /// 
    /// NOTE ON HARDWARE Z-BUFFER OCCLUSION:
    /// In modern GPU rasterization (including Unity's Built-in Render Pipeline Forward/Deferred passes),
    /// depth testing (Z-test, typically 'LEqual') is executed on every fragment:
    /// - Each incoming fragment's interpolated clip-space Z is compared against the value in the Z-buffer.
    /// - If the fragment is closer than the stored depth (closer surface), it passes the test, overwrites the
    ///   color buffer, and updates the Z-buffer with its new depth.
    /// - If the fragment is farther than the stored depth (e.g. occluded by an opaque foreground surface),
    ///   it fails the test and is discarded before writing to the framebuffer.
    /// - DepthVisualization.shader samples the camera depth texture (_CameraDepthTexture) generated by this
    ///   hardware process, displaying the resolved depth map rather than acting as a replacement rasterizer.
    /// </summary>
    public class OcclusionDemoController : MonoBehaviour
    {
        [Header("Demonstration State")]
        [Tooltip("Toggle occlusion demonstration rig visibility and calibration mode. Hotkey: 'O'")]
        [SerializeField]
        private bool isDemoActive = true;

        [Header("Rig References")]
        [Tooltip("Parent transform containing the calibration slabs and probe.")]
        public GameObject rigContainer;

        [Tooltip("Near depth occluder plate (~6m relative eye distance).")]
        public Transform nearSlab;

        [Tooltip("Mid depth occluder plate (~10m relative eye distance).")]
        public Transform midSlab;

        [Tooltip("Far depth occluder plate (~16m relative eye distance).")]
        public Transform farSlab;

        [Tooltip("Dynamic probe that oscillates behind Near Slab and in front of Mid Slab.")]
        public Transform slidingProbe;

        [Header("Dynamic Probe Motion")]
        [Tooltip("Speed of the probe's back-and-forth oscillation in radians per second.")]
        public float probeSpeed = 1.4f;

        [Tooltip("Horizontal travel distance of the oscillating probe.")]
        public float probeAmplitude = 2.4f;

        [Header("Camera Alignment")]
        [Tooltip("Automatically align camera to prime occlusion vantage point when enabled.")]
        public bool alignCameraOnEnable = false;

        private Vector3 probeInitialLocalPos;
        private OrbitCamera orbitCamera;

        public bool IsDemoActive
        {
            get => isDemoActive;
            set => SetDemoActive(value);
        }

        private void Start()
        {
            if (slidingProbe != null)
            {
                probeInitialLocalPos = slidingProbe.localPosition;
            }

            orbitCamera = FindFirstObjectByType<OrbitCamera>();
            ApplyDemoState();
        }

        private void Update()
        {
            // Hotkey 'O' to toggle Occlusion Demonstration
            if (Input.GetKeyDown(KeyCode.O))
            {
                if (!Application.isPlaying || Application.isFocused)
                {
                    ToggleOcclusionDemo();
                }
            }

            // Animate dynamic probe when active
            if (isDemoActive && slidingProbe != null)
            {
                float xOffset = Mathf.Sin(Time.time * probeSpeed) * probeAmplitude;
                slidingProbe.localPosition = probeInitialLocalPos + new Vector3(xOffset, 0f, 0f);
            }
        }

        /// <summary>
        /// Toggles the occlusion demonstration on and off.
        /// </summary>
        public void ToggleOcclusionDemo()
        {
            SetDemoActive(!isDemoActive);
        }

        /// <summary>
        /// Sets the demonstration active state, updating rig visibility and camera view.
        /// </summary>
        public void SetDemoActive(bool active)
        {
            isDemoActive = active;
            ApplyDemoState();

            if (isDemoActive)
            {
                Debug.Log("<color=#00f0ff><b>[Z-BUFFER OCCLUSION DEMO: ACTIVE]</b></color>\n" +
                          "• Near Slab (~6m) visibly occludes Mid Slab (~10m) and Far Slab (~16m).\n" +
                          "• Dynamic Probe oscillates behind Near Slab: observe pixel-perfect cutoffs!\n" +
                          "• Press [Z] to view depth gradients, [P] to pause camera, [O] to toggle rig.");

                if (alignCameraOnEnable && orbitCamera != null)
                {
                    AlignCameraToDemo();
                }
            }
            else
            {
                Debug.Log("<color=#ffff00><b>[Z-BUFFER OCCLUSION DEMO: STANDBY]</b></color> Occlusion test rig hidden.");
            }
        }

        private void ApplyDemoState()
        {
            if (rigContainer != null)
            {
                rigContainer.SetActive(isDemoActive);
            }
        }

        /// <summary>
        /// Aligns camera to the prime calibration angle where all 3 slabs visibly overlap.
        /// </summary>
        public void AlignCameraToDemo()
        {
            if (orbitCamera != null)
            {
                orbitCamera.currentYaw = -32f;
                orbitCamera.currentPitch = 12f;
                orbitCamera.distance = 15f;
            }
        }
    }
}
